"use server";

import { backend } from "@/lib/backend";
import { neonAuth } from "@/lib/neon/auth-server";
import { checkAdmin } from "@/lib/auth";
import {
  sandboxResetRedirect, validRecoveryEmail, validRecoveryPassword, validRecoveryToken,
  vercelPreviewContext,
} from "@/lib/neon/password-recovery";
import { neonSandboxConfig } from "@/lib/neon/config";

/** Official Neon Auth SDK sets HTTP-only session cookies in this Server Action. */
export async function signInNeon(email: string, password: string): Promise<{ok: boolean; error?: string}> {
  if (backend() !== "neon") return {ok:false,error:"Neon 登入尚未啟用。"};
  if (typeof email !== "string" || typeof password !== "string" ||
      email.length > 256 || password.length > 1024 || !email.includes("@") || !password) {
    return {ok:false,error:"請輸入有效的電子郵件與密碼。"};
  }
  try {
    const {error} = await neonAuth().signIn.email({email, password});
    if (error) return {ok:false,error:"登入失敗，請確認管理員帳號與密碼。"};
    return {ok:true};
  } catch {
    return {ok:false,error:"Neon Auth 暫時無法連線。"};
  }
}

/** Separate request: cookie is present in the browser, so DB RLS can verify role. */
export async function confirmNeonAdmin(): Promise<{ok:boolean;error?:string}> {
  if (backend() !== "neon") return {ok:false,error:"Neon 登入尚未啟用。"};
  const user = await checkAdmin();
  if (user) return {ok:true};
  try { await neonAuth().signOut(); } catch { /* deny access anyway */ }
  return {ok:false,error:"此帳號沒有站長權限，請改用授權的管理員帳號登入。"};
}

/** Request a Neon-issued, single-use reset link. No token is generated by us. */
export async function requestNeonPasswordReset(email: unknown): Promise<{ok:boolean;error?:string}> {
  if (backend() !== "neon") return {ok:false,error:"密碼重設尚未啟用。"};
  if (!validRecoveryEmail(email)) return {ok:false,error:"請輸入有效的電子郵件地址。"};
  try {
    // This also refuses anything except the already authorized test branch.
    neonSandboxConfig();
    const redirectTo = sandboxResetRedirect(process.env.NEXT_PUBLIC_SITE_URL || "", vercelPreviewContext());
    const {error} = await neonAuth().requestPasswordReset({email, redirectTo});
    if (error) return {ok:false,error:"暫時無法寄送重設郵件，請稍後再試。"};
    // Do not reveal whether a user exists.
    return {ok:true};
  } catch {
    return {ok:false,error:"密碼重設服務暫時無法使用。"};
  }
}

/** Better Auth validates and consumes its own reset token atomically. */
export async function completeNeonPasswordReset(
  token: unknown, newPassword: unknown,
): Promise<{ok:boolean;error?:string}> {
  if (backend() !== "neon") return {ok:false,error:"密碼重設尚未啟用。"};
  if (!validRecoveryToken(token)) return {ok:false,error:"重設連結無效或已過期，請重新申請。"};
  if (!validRecoveryPassword(newPassword)) {
    return {ok:false,error:"密碼長度需為 12–128 字元，且不可包含控制字元。"};
  }
  try {
    neonSandboxConfig();
    const {error} = await neonAuth().resetPassword({token, newPassword});
    if (error) return {ok:false,error:"重設連結無效或已過期，請重新申請。"};
    return {ok:true};
  } catch {
    return {ok:false,error:"密碼重設服務暫時無法使用。"};
  }
}
